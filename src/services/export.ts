  generatePrintHTML(report: ReportState, lang: 'ar' | 'en'): string {
    const isRTL = lang === 'ar';
    
    const styles = `
      <style>
        @media print {
          body { font-family: 'Inter', system-ui, sans-serif; }
          .page-break { page-break-after: always; }
          .no-print { display: none !important; }
        }
        body { direction: ${isRTL ? 'rtl' : 'ltr'}; }
        .report-header { text-align: center; margin-bottom: 2rem; }
        .report-section { margin-bottom: 1.5rem; }
        .section-title { font-size: 1.25rem; font-weight: 700; margin-bottom: 0.5rem; }
        .section-content { line-height: 1.6; }
        .report-footer { text-align: center; margin-top: 2rem; font-size: 0.75rem; color: #666; }
      </style>
    `;

    const header = `
      <div class="report-header">
        <h1>${report.name}</h1>
        <p>${new Date().toLocaleDateString(lang === 'ar' ? 'ar-EG' : 'en-US')}</p>
      </div>
    `;

    const sections = report.blocks
      .filter(b => b.visible)
      .sort((a, b) => a.order - b.order)
      .map(block => `
        <div class="report-section">
          ${block.title ? `<h2 class="section-title">${block.title[lang]}</h2>` : ''}
          ${block.content ? `<div class="section-content">${block.content[lang]}</div>` : ''}
        </div>
      `)
      .join('');

    const footer = `
      <div class="report-footer">
        <p>HORUS AI Platform - ${lang === 'ar' ? 'منصة تحليل البيانات الذكية' : 'Smart Data Analytics Platform'}</p>
      </div>
    `;

    return `
      <!DOCTYPE html>
      <html lang="${lang}" dir="${isRTL ? 'rtl' : 'ltr'}">
      <head>
        <meta charset="UTF-8">
        <meta name="viewport" content="width=device-width, initial-scale=1.0">
        <title>${report.name}</title>
        ${styles}
      </head>
      <body>
        ${header}
        ${sections}
        ${footer}
      </body>
      </html>
    `;
  }

  openPrintPreview(report: ReportState, lang: 'ar' | 'en'): void {
    const html = this.generatePrintHTML(report, lang);
    const printWindow = window.open('', '_blank');
    if (printWindow) {
      printWindow.document.write(html);
      printWindow.document.close();
      printWindow.onload = () => {
        printWindow.print();
      };
    }
  }

  // ============================================================================
  // CSV EXPORT
  // ============================================================================

  exportToCSV(data: Record<string, unknown>[], filename: string): ExportResult {
    try {
      if (!data.length) {
        return { success: false, error: 'No data to export' };
      }

      const headers = Object.keys(data[0]);
      const rows = data.map(row => 
        headers.map(h => {
          const val = row[h];
          // Escape commas and quotes
          if (typeof val === 'string' && (val.includes(',') || val.includes('"'))) {
            return `"${val.replace(/"/g, '""')}"`;
          }
          return String(val ?? '');
        }).join(',')
      );

      const csv = [headers.join(','), ...rows].join('\n');
      const blob = new Blob(['\ufeff' + csv], { type: 'text/csv;charset=utf-8;' });
      const url = URL.createObjectURL(blob);

      // Trigger download
      const a = document.createElement('a');
      a.href = url;
      a.download = `${filename}.csv`;
      a.click();
      URL.revokeObjectURL(url);

      return { success: true, url };
    } catch (error) {
      return {
        success: false,
        error: error instanceof Error ? error.message : 'CSV export failed',
      };
    }
  }

